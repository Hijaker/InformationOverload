function M.context(c,templates)
    if not c then return false end
    local t=templates and templates[c.weapon]
    return c.grenade==true or M.templates[c.weapon]==true or t and t.is_grenade_ability_weapon==true or false
end
-- Existing dedicated Psyker buckets are selected by the caller before exclusion.
function M.excluded(profile,context)
    return M.profiles[profile]~=nil or M.context(context)
end
return M
